/**
 * content-regenerator.js - Handle content regeneration with LLMs based on user corrections
 */

class ContentRegenerator {
  constructor() {
    this.llmAPI = window.llmAPI || new LLMAPIManager();
  }

  /**
   * Regenerate content based on original and correction
   */
  async regenerate(originalContent, correction, llmType = 'claude') {
    const prompt = this.buildPrompt(originalContent, correction);

    let result;
    switch (llmType) {
      case 'claude':
        result = await this.llmAPI.callClaude(prompt);
        break;
      case 'openai':
        result = await this.llmAPI.callOpenAI(prompt);
        break;
      case 'gemini':
        result = await this.llmAPI.callGemini(prompt);
        break;
      default:
        return { error: 'Invalid LLM type' };
    }

    if (result.success) {
      return {
        success: true,
        regenerated: result.text,
        implications: this.analyzeImplications(originalContent, correction, result.text)
      };
    } else {
      return result;
    }
  }

  /**
   * Build prompt for content regeneration
   */
  buildPrompt(originalContent, correction) {
    return `I have educational content about Latino women's rhetoric that needs updating based on user feedback.

Original content:
"""
${originalContent}
"""

User correction/addition:
"""
${correction}
"""

Please regenerate the content incorporating this correction while:
1. Maintaining the educational tone
2. Preserving cultural sensitivity
3. Integrating the new information seamlessly
4. Ensuring accuracy

Regenerated content:`;
  }

  /**
   * Analyze algorithmic implications of regeneration
   */
  analyzeImplications(original, correction, regenerated) {
    // Simple analysis - could be enhanced with more sophisticated comparison
    const implications = [];

    if (regenerated.length < original.length * 0.8) {
      implications.push('Content was significantly condensed—information may have been lost');
    }

    if (regenerated.length > original.length * 1.5) {
      implications.push('Content was significantly expanded—verify accuracy of additions');
    }

    // Check if correction terms appear in regenerated content
    const correctionWords = correction.toLowerCase().split(/\s+/);
    const regeneratedLower = regenerated.toLowerCase();
    const included = correctionWords.filter(word => regeneratedLower.includes(word)).length;
    const ratio = included / correctionWords.length;

    if (ratio < 0.5) {
      implications.push('Many terms from your correction are not present in regenerated content');
    }

    if (implications.length === 0) {
      implications.push('Content appears to integrate correction appropriately');
    }

    return implications;
  }
}

// Set up regeneration demo if on contribute page
document.addEventListener('DOMContentLoaded', () => {
  const regenBtn = document.getElementById('show-regen-demo');
  const regenSection = document.getElementById('regen-demo-section');

  if (regenBtn && regenSection) {
    regenBtn.addEventListener('click', () => {
      regenSection.hidden = !regenSection.hidden;
      regenBtn.textContent = regenSection.hidden ?
        'Try Content Regeneration Demo' :
        'Hide Regeneration Demo';
    });
  }

  const regenerateBtn = document.getElementById('regenerate-btn');
  if (regenerateBtn) {
    regenerateBtn.addEventListener('click', async () => {
      const original = document.getElementById('original-content').value;
      const correction = document.getElementById('correction-input').value;

      if (!correction) {
        alert('Please enter a correction or addition');
        return;
      }

      const outputDiv = document.getElementById('regenerated-output');
      const implicationsDiv = document.getElementById('algorithmic-implications');

      outputDiv.innerHTML = '<div class="loading-message">Regenerating content...</div>';
      regenerateBtn.disabled = true;

      const regenerator = new ContentRegenerator();
      const result = await regenerator.regenerate(original, correction, 'claude');

      if (result.success) {
        outputDiv.innerHTML = `
          <div class="comparison-output">
            <div class="output-section">
              <h5>Original</h5>
              <p>${window.utils.sanitizeHTML(original)}</p>
            </div>
            <div class="output-section">
              <h5>Your Correction</h5>
              <p>${window.utils.sanitizeHTML(correction)}</p>
            </div>
            <div class="output-section">
              <h5>Regenerated by LLM</h5>
              <p>${window.utils.sanitizeHTML(result.regenerated)}</p>
            </div>
          </div>
        `;

        implicationsDiv.innerHTML = `
          <p><strong>What happened algorithmically:</strong></p>
          <ul>
            ${result.implications.map(imp => `<li>${window.utils.sanitizeHTML(imp)}</li>`).join('')}
          </ul>
          <p><strong>Important note:</strong> This demonstrates how LLMs process corrections. All actual content updates are reviewed by humans before being incorporated into the site.</p>
        `;
        implicationsDiv.hidden = false;
      } else {
        outputDiv.innerHTML = `
          <div class="error-message">
            <p>Error: ${window.utils.sanitizeHTML(result.error || 'Failed to regenerate content')}</p>
            <p>Make sure you have configured an API key in the Demonstrations page.</p>
          </div>
        `;
        implicationsDiv.hidden = true;
      }

      regenerateBtn.disabled = false;
    });
  }
});

// Export for modules
if (typeof module !== 'undefined' && module.exports) {
  module.exports = ContentRegenerator;
}
